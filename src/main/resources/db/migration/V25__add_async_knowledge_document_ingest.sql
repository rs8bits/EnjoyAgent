ALTER TABLE knowledge_document
    ADD COLUMN processing_attempts INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN processing_started_at TIMESTAMPTZ,
    ADD COLUMN completed_at TIMESTAMPTZ,
    ADD COLUMN next_retry_at TIMESTAMPTZ,
    ADD COLUMN last_error_code VARCHAR(64),
    ADD COLUMN last_error_message VARCHAR(1000);

CREATE INDEX idx_knowledge_document_processing
    ON knowledge_document (status, next_retry_at, id);

CREATE TABLE knowledge_ingest_outbox
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id      BIGINT       NOT NULL,
    delivery_attempt INTEGER      NOT NULL,
    payload          TEXT         NOT NULL,
    status           VARCHAR(32)  NOT NULL,
    publish_attempts INTEGER      NOT NULL DEFAULT 0,
    available_at     TIMESTAMPTZ  NOT NULL,
    claimed_at       TIMESTAMPTZ,
    published_at     TIMESTAMPTZ,
    last_error       VARCHAR(1000),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_knowledge_ingest_outbox_document
        FOREIGN KEY (document_id) REFERENCES knowledge_document (id) ON DELETE CASCADE,
    CONSTRAINT uk_knowledge_ingest_outbox_delivery
        UNIQUE (document_id, delivery_attempt)
);

CREATE INDEX idx_knowledge_ingest_outbox_due
    ON knowledge_ingest_outbox (status, available_at, id);
