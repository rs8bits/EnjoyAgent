-- 客服长期记忆只保存一份“有损摘要”，完整消息仍然保留在 support_message。
-- conversation_id 单独唯一，保证一个用户在一个租户中的唯一客服会话只有一份摘要。
CREATE TABLE support_conversation_memory
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id          BIGINT      NOT NULL,
    tenant_id                BIGINT      NOT NULL,
    user_id                  BIGINT      NOT NULL,
    summary                  TEXT        NOT NULL,
    -- 摘要已经完整覆盖到的消息 sequence。上下文只读取该水位之后的原始消息，
    -- 从而避免同一段对话既以摘要形式出现、又以原文形式重复注入模型。
    covered_through_sequence BIGINT      NOT NULL DEFAULT 0,
    -- 由 JPA @Version 自动维护。两个实例同时刷新时，旧快照不能覆盖新摘要。
    version                  BIGINT      NOT NULL DEFAULT 0,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_support_conversation_memory_conversation FOREIGN KEY (conversation_id)
        REFERENCES support_conversation (id) ON DELETE CASCADE,
    CONSTRAINT fk_support_conversation_memory_tenant FOREIGN KEY (tenant_id)
        REFERENCES tenant (id),
    CONSTRAINT fk_support_conversation_memory_user FOREIGN KEY (user_id)
        REFERENCES app_user (id),
    CONSTRAINT uk_support_conversation_memory_conversation UNIQUE (conversation_id),
    CONSTRAINT ck_support_conversation_memory_sequence_non_negative
        CHECK (covered_through_sequence >= 0),
    CONSTRAINT ck_support_conversation_memory_summary_not_blank
        CHECK (LENGTH(BTRIM(summary)) > 0)
);

-- 所有读取都同时携带 tenant、user、conversation 三个边界字段。这个索引既服务
-- 常规读取，也使数据库执行计划清楚体现摘要不能跨租户或跨用户查询。
CREATE INDEX idx_support_conversation_memory_scope
    ON support_conversation_memory (tenant_id, user_id, conversation_id);
