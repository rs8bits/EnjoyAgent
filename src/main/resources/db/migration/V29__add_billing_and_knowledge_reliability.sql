ALTER TABLE user_wallet
    ADD COLUMN reserved_amount DECIMAL(18, 6) NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_user_wallet_reserved_amount_nonnegative CHECK (reserved_amount >= 0),
    ADD CONSTRAINT ck_user_wallet_reserved_within_balance
        CHECK (balance >= 0 AND reserved_amount <= balance) NOT VALID;

CREATE TABLE billing_credit_reservation
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  BIGINT         NOT NULL,
    official_model_config_id BIGINT         NOT NULL,
    reserved_amount          DECIMAL(18, 6) NOT NULL,
    status                   VARCHAR(32)    NOT NULL DEFAULT 'ACTIVE',
    expires_at               TIMESTAMPTZ    NOT NULL,
    linked_at                TIMESTAMPTZ,
    release_claimed_at       TIMESTAMPTZ,
    released_at              TIMESTAMPTZ,
    created_at               TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_billing_credit_reservation_user
        FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_billing_credit_reservation_model
        FOREIGN KEY (official_model_config_id) REFERENCES official_model_config (id),
    CONSTRAINT ck_billing_credit_reservation_amount_positive CHECK (reserved_amount > 0)
);

CREATE INDEX idx_billing_credit_reservation_active
    ON billing_credit_reservation (user_id, official_model_config_id, id)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_billing_credit_reservation_expiry
    ON billing_credit_reservation (status, expires_at, release_claimed_at, user_id, id)
    WHERE status IN ('ACTIVE', 'RELEASING');

ALTER TABLE billing_usage_event
    ADD COLUMN reservation_id BIGINT,
    ADD COLUMN usage_estimated BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN processing_attempts INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN next_retry_at TIMESTAMPTZ,
    ADD CONSTRAINT fk_billing_usage_event_reservation
        FOREIGN KEY (reservation_id) REFERENCES billing_credit_reservation (id),
    ADD CONSTRAINT uk_billing_usage_event_reservation UNIQUE (reservation_id);

CREATE TABLE billing_usage_outbox
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_event_id   BIGINT        NOT NULL,
    status           VARCHAR(32)   NOT NULL DEFAULT 'PENDING',
    publish_attempts INTEGER       NOT NULL DEFAULT 0,
    available_at     TIMESTAMPTZ   NOT NULL,
    claimed_at       TIMESTAMPTZ,
    published_at     TIMESTAMPTZ,
    last_error       VARCHAR(1000),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_billing_usage_outbox_event
        FOREIGN KEY (usage_event_id) REFERENCES billing_usage_event (id) ON DELETE CASCADE,
    CONSTRAINT uk_billing_usage_outbox_event UNIQUE (usage_event_id)
);

CREATE INDEX idx_billing_usage_outbox_due
    ON billing_usage_outbox (status, available_at, claimed_at, id);

CREATE UNIQUE INDEX uk_user_wallet_transaction_recharge_order
    ON user_wallet_transaction (transaction_type, reference_type, reference_id)
    WHERE transaction_type = 'RECHARGE_APPROVED'
      AND reference_type = 'RECHARGE_ORDER'
      AND reference_id IS NOT NULL;

