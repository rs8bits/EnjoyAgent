CREATE TABLE chat_turn_request
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL,
    user_id            BIGINT       NOT NULL,
    session_id         BIGINT       NOT NULL,
    idempotency_key    VARCHAR(128) NOT NULL,
    request_hash       VARCHAR(64)  NOT NULL,
    owner_token        VARCHAR(36),
    status             VARCHAR(16)  NOT NULL,
    response_json      TEXT,
    user_message_id    BIGINT,
    lease_expires_at   TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_chat_turn_request_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
    CONSTRAINT fk_chat_turn_request_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_chat_turn_request_session FOREIGN KEY (session_id) REFERENCES chat_session (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_turn_request_user_message FOREIGN KEY (user_message_id) REFERENCES chat_message (id) ON DELETE SET NULL,
    CONSTRAINT uk_chat_turn_request_session_key UNIQUE (session_id, idempotency_key),
    CONSTRAINT uk_chat_turn_request_user_message UNIQUE (user_message_id),
    CONSTRAINT ck_chat_turn_request_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED'))
);

CREATE UNIQUE INDEX uk_chat_turn_request_one_running_per_session
    ON chat_turn_request (session_id)
    WHERE status = 'RUNNING';

CREATE INDEX idx_chat_turn_request_lease ON chat_turn_request (lease_expires_at)
    WHERE status = 'RUNNING';
