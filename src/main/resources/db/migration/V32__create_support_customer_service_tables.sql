-- AI 客服会话与普通 Agent 会话属于两个业务域，因此使用独立表保存。
-- 一个用户在一个租户中只有一个长期客服会话；切换租户后会得到另一条会话，
-- 从数据库约束层阻止跨租户记忆串线。
CREATE TABLE support_conversation
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT      NOT NULL,
    user_id               BIGINT      NOT NULL,
    last_message_sequence BIGINT      NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_support_conversation_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
    CONSTRAINT fk_support_conversation_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT uk_support_conversation_tenant_user UNIQUE (tenant_id, user_id),
    CONSTRAINT ck_support_conversation_sequence_non_negative CHECK (last_message_sequence >= 0)
);

CREATE INDEX idx_support_conversation_user ON support_conversation (user_id);
CREATE INDEX idx_support_conversation_updated_at ON support_conversation (updated_at DESC);

-- 一次用户提问对应一个 turn。幂等键只在当前长期会话中唯一；request_hash
-- 用来阻止客户端错误地复用同一幂等键发送不同内容。
CREATE TABLE support_turn
(
    id                       UUID         PRIMARY KEY,
    conversation_id          BIGINT       NOT NULL,
    idempotency_key          VARCHAR(128) NOT NULL,
    request_hash             VARCHAR(64)  NOT NULL,
    -- 每次执行/重试都会更换 owner_token。旧工作线程即使在租约接管后恢复，
    -- 也无法再修改新执行者拥有的 Turn，这个令牌属于并发栅栏而不是用户凭证。
    owner_token              UUID         NOT NULL,
    -- @Version 提供数据库更新层的第二道并发保护；owner_token 负责识别执行者，
    -- version 负责发现两个事务基于同一旧快照同时写入。
    version                  BIGINT       NOT NULL DEFAULT 0,
    status                   VARCHAR(16)  NOT NULL,
    intent_code              VARCHAR(64),
    route_type               VARCHAR(16),
    model_provider           VARCHAR(32),
    model_name               VARCHAR(128),
    official_model_config_id BIGINT,
    model_latency_ms         BIGINT,
    prompt_tokens            INTEGER,
    completion_tokens        INTEGER,
    total_tokens             INTEGER,
    error_code               VARCHAR(64),
    error_message            VARCHAR(512),
    lease_expires_at         TIMESTAMPTZ,
    completed_at             TIMESTAMPTZ,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_support_turn_conversation FOREIGN KEY (conversation_id)
        REFERENCES support_conversation (id),
    CONSTRAINT uk_support_turn_conversation_key UNIQUE (conversation_id, idempotency_key),
    CONSTRAINT ck_support_turn_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_support_turn_route CHECK (route_type IS NULL OR route_type IN ('RULE', 'SKILL', 'LLM'))
);

-- 会话内只允许一轮处于 RUNNING。应用层会先锁会话并给出友好错误；这个部分唯一
-- 索引是多实例并发下的最后一道防线。
CREATE UNIQUE INDEX uk_support_turn_one_running_per_conversation
    ON support_turn (conversation_id)
    WHERE status = 'RUNNING';

CREATE INDEX idx_support_turn_conversation_created
    ON support_turn (conversation_id, created_at DESC);
CREATE INDEX idx_support_turn_lease
    ON support_turn (lease_expires_at)
    WHERE status = 'RUNNING';

-- sequence 是会话内稳定游标，不依赖时间戳精度，也不会像 offset 分页一样因新消息
-- 插入而漂移。完整用户消息和最终助手消息都保存在这里。
CREATE TABLE support_message
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL,
    turn_id         UUID        NOT NULL,
    sequence        BIGINT      NOT NULL,
    role            VARCHAR(16) NOT NULL,
    content         TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_support_message_conversation FOREIGN KEY (conversation_id)
        REFERENCES support_conversation (id),
    CONSTRAINT fk_support_message_turn FOREIGN KEY (turn_id)
        REFERENCES support_turn (id),
    CONSTRAINT uk_support_message_conversation_sequence UNIQUE (conversation_id, sequence),
    CONSTRAINT ck_support_message_role CHECK (role IN ('USER', 'ASSISTANT'))
);

CREATE INDEX idx_support_message_conversation_sequence
    ON support_message (conversation_id, sequence DESC);
CREATE INDEX idx_support_message_turn ON support_message (turn_id);

-- 每次 Skill 尝试单独归档。request_payload 和 result_payload 只能写入经过
-- BEFORE_ARCHIVE Hook 脱敏后的 JSON；绝不能把真实 API Key、Cookie 或授权令牌写入。
CREATE TABLE support_skill_call
(
    id               UUID         PRIMARY KEY,
    conversation_id  BIGINT       NOT NULL,
    turn_id          UUID         NOT NULL,
    tenant_id        BIGINT       NOT NULL,
    user_id          BIGINT       NOT NULL,
    call_index       INTEGER      NOT NULL,
    skill_name       VARCHAR(128) NOT NULL,
    skill_version    VARCHAR(32)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    request_payload  TEXT,
    result_payload   TEXT,
    display_summary  VARCHAR(1000),
    error_code       VARCHAR(64),
    error_message    VARCHAR(512),
    duration_ms      BIGINT,
    finished_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_support_skill_call_conversation FOREIGN KEY (conversation_id)
        REFERENCES support_conversation (id),
    CONSTRAINT fk_support_skill_call_turn FOREIGN KEY (turn_id)
        REFERENCES support_turn (id),
    CONSTRAINT fk_support_skill_call_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
    CONSTRAINT fk_support_skill_call_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT uk_support_skill_call_turn_index UNIQUE (turn_id, call_index),
    CONSTRAINT ck_support_skill_call_status CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED'))
);

CREATE INDEX idx_support_skill_call_scope_created
    ON support_skill_call (tenant_id, user_id, created_at DESC);
CREATE INDEX idx_support_skill_call_turn ON support_skill_call (turn_id, call_index);
