CREATE TABLE workflow_execution
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id     BIGINT        NOT NULL,
    tenant_id       BIGINT        NOT NULL,
    trigger_type    VARCHAR(16)   NOT NULL,
    status          VARCHAR(16)   NOT NULL,
    input_json      TEXT,
    output_json     TEXT,
    node_count      INTEGER       NOT NULL DEFAULT 0,
    executed_count  INTEGER       NOT NULL DEFAULT 0,
    duration_ms     BIGINT,
    error_message   VARCHAR(1000),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    completed_at    TIMESTAMPTZ,
    CONSTRAINT fk_workflow_exec_workflow FOREIGN KEY (workflow_id) REFERENCES workflow (id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_exec_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id)
);

CREATE INDEX idx_workflow_exec_workflow_id ON workflow_execution (workflow_id);
CREATE INDEX idx_workflow_exec_created_at ON workflow_execution (created_at DESC);
