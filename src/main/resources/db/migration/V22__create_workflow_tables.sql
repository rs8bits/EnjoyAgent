CREATE TABLE workflow
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT        NOT NULL,
    name        VARCHAR(128)  NOT NULL,
    description VARCHAR(512),
    enabled     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_workflow_tenant FOREIGN KEY (tenant_id) REFERENCES tenant (id),
    CONSTRAINT uk_workflow_tenant_name UNIQUE (tenant_id, name)
);

CREATE INDEX idx_workflow_tenant_id ON workflow (tenant_id);

CREATE TABLE workflow_node
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT        NOT NULL,
    name        VARCHAR(128)  NOT NULL,
    node_type   VARCHAR(32)   NOT NULL,
    config_json TEXT          NOT NULL DEFAULT '{}',
    position_x  INTEGER       NOT NULL DEFAULT 0,
    position_y  INTEGER       NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_workflow_node_workflow FOREIGN KEY (workflow_id) REFERENCES workflow (id) ON DELETE CASCADE
);

CREATE INDEX idx_workflow_node_workflow_id ON workflow_node (workflow_id);

CREATE TABLE workflow_edge
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id     BIGINT        NOT NULL,
    source_node_id  BIGINT        NOT NULL,
    target_node_id  BIGINT        NOT NULL,
    source_handle   VARCHAR(64),
    target_handle   VARCHAR(64),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_workflow_edge_workflow FOREIGN KEY (workflow_id) REFERENCES workflow (id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_edge_source FOREIGN KEY (source_node_id) REFERENCES workflow_node (id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_edge_target FOREIGN KEY (target_node_id) REFERENCES workflow_node (id) ON DELETE CASCADE
);

CREATE INDEX idx_workflow_edge_workflow_id ON workflow_edge (workflow_id);
